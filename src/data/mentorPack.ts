/**
 * Шкала готовности: ответ меньше десяти — сразу добираем баллы.
 * Наставник: «я спрашиваю, насколько важно, а не сомневаетесь ли вы».
 */
export function scaleFollowUp(text: string): string | null {
  const match = /(\d{1,2})\s*(?:из\s*10|балл|\/\s*10)/i.exec(text)
  const score = match ? Number(match[1]) : NaN
  if (!Number.isFinite(score) || score < 1 || score >= 10) return null
  return `Вы сказали ${score}. А где потерялись остальные ${10 - score}? Только уточню: я спрашиваю не про сомнения в нас, а про то, насколько для вас важно решить этот вопрос. Это разные вопросы.`
}

