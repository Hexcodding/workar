/** Красные флаги из фидбека Антона */
export function scanPersonalAlerts(input: {
  recentText: string
  fullText: string
  /** последние слова мамы: по ним ловятся возражения */
  clientText?: string
  /** последние свои слова: по ним ловятся собственные промахи */
  sellerText?: string
  checked: Record<string, boolean>
  elapsedMin: number
  metrics?: DialogMetrics
}): CoachAlert[] {
  const { recentText, fullText, clientText, sellerText, checked, elapsedMin, metrics } = input
  const alerts: CoachAlert[] = []
  const full = fullText.toLowerCase()
  // пока каналы не разделены, оба сводятся к общему тексту — как было раньше
  const mine = (sellerText ?? recentText).toLowerCase()
  const hers = (clientText ?? recentText).toLowerCase()

  const hasPointB = checked.p3 || /точк[ауи]\s*б|представьте|почувствуете/.test(full)
  const hasScale = checked.p4 || /от\s*0\s*до\s*10|десятибальн|почему не/.test(full)
  const hasPreclose =
    checked.pi3 ||
    (/что понравилось/.test(full) && /достоин/.test(full) && /готов[аы]/.test(full))
  const talkingPrice = /стоим|тысяч|рассрочк|в месяц|оплат|5000|119|209|8708/.test(mine)
  const crmPressure =
    /crm|закроется|только (сегодня|на диагностике)|услови[яе].*только|заявк[а-яё]*\s+(закрыв|удерж)|бонус[а-яё]*.{0,40}только|на сайте.{0,30}без бонус/i.test(
      mine,
    )
  const arguing =
    /дети реагируют|ребёнок на самом деле захочет|ещ[её] обучение\??\s*нет/.test(mine)
  // «обсудим» и «поговорите с дочкой» Егор произносит по десять раз за встречу,
  // поэтому здесь только то, чем мама действительно откладывает решение
  const thinkObjection =
    /(надо|нужно|хочу|давайте|дайте|я)\s+(ещ[её]\s+)?подума|подумаем|мы подума|посоветоваться|посоветуюсь|обсудить с (мужем|папой|супруг|семь[её]й)|с мужем (поговор|обсу|посовет)|время подумать/.test(
      hers,
    )

  if (metrics) {
    if (metrics.monologue && elapsedMin >= 4) {
      alerts.push({
        id: 'monologue',
        level: 'critical',
        title: `Монолог ${Math.round(metrics.sellerShare * 100)}%`,
        text: 'Ты говоришь почти один. Верни диалог открытым вопросом.',
        say: 'Я много рассказываю — остановлюсь. А как вы сами это видите? Что для вас здесь важнее всего?',
      })
    }

    if (metrics.clientAudible && metrics.silenceSec > 60 && elapsedMin >= 4 && !metrics.monologue) {
      alerts.push({
        id: 'client-silent',
        level: 'warn',
        title: `Клиент молчит ${metrics.silenceSec}с`,
        text: 'Проверь контакт и верни маму в разговор.',
        say: 'Скажите, вам сейчас всё понятно или что-то стоит разобрать подробнее?',
      })
    }

    if (metrics.clientCooling) {
      alerts.push({
        id: 'client-cooling',
        level: 'critical',
        title: 'Клиент остыл',
        text: 'Короткие «угу / понятно» — это дорога в «подумаю». Вскрывай сейчас.',
        say: 'Чувствую, вы стали отвечать короче. Скажите честно — что сейчас вызывает сомнение?',
      })
    }

    if (
      metrics.clientAudible &&
      metrics.sellerQuestions === 0 &&
      metrics.utterances >= 5 &&
      elapsedMin >= 6 &&
      !metrics.monologue &&
      // мама сама рассказывает — подгонять вопросами тут нечего, надо слушать
      metrics.clientShare < 0.6
    ) {
      alerts.push({
        id: 'no-questions',
        level: 'warn',
        title: 'Нет вопросов',
        text: 'За последние полторы минуты ты не задал ни одного вопроса.',
        say: 'А что для вас в этой ситуации самое неприятное сейчас?',
      })
    }
  }

  if (elapsedMin >= 3 && elapsedMin <= 12 && !checked.g5 && !/кто.*(решени|принимает)|вместе с/.test(full)) {
    alerts.push({
      id: 'lpr',
      level: 'critical',
      title: 'ЛПР не квалифицирован',
      text: 'В первые минуты выясни, кто принимает решение и все ли на связи.',
      say: 'Скажите, решение о занятиях вы принимаете сами или вместе с ребёнком/супругом? Все ли сегодня на связи?',
    })
  }

  if (elapsedMin >= 15 && !hasPointB) {
    alerts.push({
      id: 'pointb',
      level: 'critical',
      title: 'Нет точки Б',
      text: 'Не уходи в презу, пока не оцифруешь желаемый результат словами мамы.',
      say: 'А как для вас выглядит идеальная картина через полгода? По каким признакам поймёте, что всё получилось?',
    })
  }

  if (hasPointB && !hasScale && elapsedMin >= 18) {
    alerts.push({
      id: 'scale',
      level: 'warn',
      title: 'Сними шкалу 0–10',
      text: 'Зафиксируй важность и спроси «почему не 10?» — вытащит скрытое возражение.',
      say: 'По шкале от 0 до 10, насколько важно решить это сейчас? Почему не 10?',
    })
  }

  if (talkingPrice && !hasPointB) {
    alerts.push({
      id: 'price-no-b',
      level: 'critical',
      title: 'Цена без точки Б',
      text: 'Стоп. Сначала верни мечту клиента, потом цифру.',
      say: 'Вы хотели [её слова]. Именно это вы получаете за эти деньги. Как вам такие условия?',
    })
  }

  if (talkingPrice && hasPointB && !hasPreclose) {
    alerts.push({
      id: 'preclose',
      level: 'critical',
      title: 'Нет 4 вопросов до цены',
      text: 'До цены проведи все 4 с паузами на ответ.',
      say: 'Как вам такой подход? / Что понравилось больше всего? / Достоин ли ребёнок? / Готовы начать?',
    })
  }

  if (crmPressure) {
    alerts.push({
      id: 'crm',
      level: 'critical',
      title: 'Не дави CRM-дедлайном',
      text: 'Антон: дедлайн только после ценности, как выгода — не как техотговорка.',
      say: 'Условия диагностики держатся до … Это лучшая цена. Успеем оформить, пока действует?',
    })
  }

  if (arguing) {
    alerts.push({
      id: 'argue',
      level: 'critical',
      title: 'Спор с родителем',
      text: 'Присоединись и уточни истину. Не спорь про её ребёнка.',
      say: 'Понимаю. Скажите честно — вас останавливает программа, стоимость или сомнение “надо ли ребёнку”?',
    })
  }

  if (thinkObjection) {
    alerts.push({
      id: 'think',
      level: 'warn',
      title: '«Подумаю / посоветуюсь»',
      text: 'Не спорь и не жми. Вскрой причину или подключи ЛПР сейчас.',
      say: 'Понимаю, решение серьёзное. Что именно хотите обсудить — программу, деньги или “надо ли”? Можем набрать второго ЛПР прямо сейчас на 5 минут.',
    })
  }

  if (elapsedMin >= 35 && !checked.pi1 && /модул|преподавател|платформ/.test(full)) {
    alerts.push({
      id: 'pitch-long',
      level: 'warn',
      title: 'Преза тянется',
      text: 'Режь до блоков «боль → решение → вопрос». Не читай всех преподавателей.',
      say: 'Вы говорили про [боль] — вот как мы это закрываем. Как вам этот блок?',
    })
  }

  return alerts
}

export function detectItemHits(text: string): string[] {
  const hits: string[] = []
  for (const rule of DETECT_RULES) {
    let n = 0
    for (const re of rule.patterns) {
      if (re.test(text)) n += 1
    }
    if (n >= (rule.minHits ?? 1)) hits.push(rule.itemId)
  }
  return hits
}

export function guessStageFromText(text: string, checked: Record<string, boolean>): string {
  const t = text.toLowerCase()
  if (/заявк|оформим|анкет|куратор/.test(t) && checked.f1) return 'close'
  if (/стоим|рассрочк|тысяч|в месяц|оплат/.test(t)) return 'finance'
  if (/подума|посовету|с мужем|возраж|сравни/.test(t)) return 'objections'
  if (/что понравилось|достоин|готовы начать|технологичн|курс развития|колесо/.test(t))
    return 'pitch'
  if (/точк|представьте|шкал|от 0 до 10|беспоко|мотивац/.test(t)) return 'pains'
  return 'greeting'
}
