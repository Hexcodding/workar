export type DossierEntry = {
  field: DossierField
  /** короткая суть для строки карточки */
  value: string
  /** как это прозвучало на самом деле */
  quote: string
  role: Role
  at: number
  /**
   * said — мама сама назвала тему,
   * agreed — вывод проговорил Егор, мама подтвердила,
   * reply — короткий ответ на вопрос Егора, тема взята из вопроса
   */
  source: 'said' | 'agreed' | 'reply'
}

export type Dossier = {
  entries: DossierEntry[]
  bySection: Array<{ section: DossierSection; entries: DossierEntry[] }>
  missing: DossierField[]
  done: number
  total: number
  /** точка Б считается найденной, когда мама сама сказала, чего хочет */
  pointBFound: boolean
}

const SECTIONS: DossierSection[] = ['who', 'study', 'behavior', 'feelings', 'family', 'goal', 'deal']

/** Мама согласилась с тем, что сказал Егор */
const AGREE = /^(да|ага|угу|мгм|конечно|верно|точно|именно|правильно|естественно|так и есть|совершенно верно)(?![а-яё])/i
const DISAGREE = /^(нет|не |да нет|не совсем|не так|вообще-то)/i

/**
 * Егор проверяет, правильно ли понял: «получается, хотите, чтобы сама училась,
 * да?». Мама на такое отвечает одним «да», и без этой связки из карточки
 * выпадает половина разговора — в том числе точка Б, которую он чаще всего
 * формулирует сам, а мама только соглашается.
 */
const CHECKING = /(да\?|верно\?|правильно\?|так\?|получается|то есть|правильно понимаю|я так понимаю|правильно услышал|вас услышал)/i

/** Сколько реплик мамы после вопроса ещё считаем ответом на него */
const ANSWER_TURNS = 3
/** И сколько секунд: дальше это уже другой разговор */
const ANSWER_SEC = 90

/**
 * Заполняем по репликам мамы и ребёнка, свежие важнее ранних:
 * к концу разговора мама уточняет то, что в начале сказала вскользь.
 * Сказанное прямо надёжнее подтверждения, подтверждение — надёжнее ответа
 * на вопрос, и перебить поле можно только источником не хуже.
 */
const TRUST: Record<DossierEntry['source'], number> = { said: 3, agreed: 2, reply: 1 }

/** Поля, чьи приметы прозвучали прямо в этой реплике */
function matches(
  text: string,
  role: Role,
  at: number,
  source: 'said' | 'agreed',
): DossierEntry[] {
  const out: DossierEntry[] = []
  for (const field of DOSSIER_FIELDS) {
    const cues = role === 'kid' && field.kidCues ? [...field.cues, ...field.kidCues] : field.cues
    const cue = cues.find((re) => re.test(text))
    if (!cue) continue
    const quote = sentence(text, cue)
    const value = field.value?.(quote) ?? field.value?.(text) ?? quote
    out.push({ field, value: value.slice(0, 160), quote, role, at, source })
  }
  return out
}

/** Слова с большой буквы, которые именами не являются */
const NOT_NAME =
  /^(Парта|Парте|Парту|Егор|Россия|Москва|Сбер|Тинькофф|Альфа|Вконтакте|Телеграм|Ватсап|Авито|Огэ|Егэ|Впр|Здравствуйте|Смотрите|Подскажите|Спасибо|Хорошо|Отлично|Понятно|Давайте|Скажите|Расскажите)$/i

/**
 * Имена по обращениям.
 *
 * Мама редко отвечает «его зовут Артём» — она говорит «Артём» один раз, и в
 * ленте это теряется. Зато Егор весь час зовёт ребёнка по имени, и имя всегда
 * с большой буквы: слово, которое ни разу не встретилось со строчной, — это
 * почти наверняка имя. Кто из двоих ребёнок, видно по «ты»: к маме он на «вы».
 */
export function guessNames(utterances: Utterance[]): { kid?: string; mom?: string } {
  const lower = new Set<string>()
  const seen = new Map<string, { kid: number; mom: number; all: number; inside: number }>()

  for (const u of utterances) {
    for (const w of u.text.match(/[а-яёa-z]{3,}/g) ?? []) lower.add(w)
  }

  for (const u of utterances) {
    if (u.role !== 'seller') continue
    const you = /(?<![а-яё])(ты|тебе|тебя|твой|твоя|тво[её])(?![а-яё])/i.test(u.text)
    const polite = /(?<![а-яё])(вы|вас|вам|ваш|ваша|ваше)(?![а-яё])/i.test(u.text)

    for (const part of u.text.split(SPLIT)) {
      const trimmed = part.trim()
      const words = trimmed.match(/[А-ЯЁ][а-яё]{2,}/g) ?? []
      const first = trimmed.match(/^[А-ЯЁ][а-яё]{2,}/)?.[0]
      for (const w of words) {
        if (NOT_NAME.test(w) || lower.has(w.toLowerCase())) continue
        const e = seen.get(w) ?? { kid: 0, mom: 0, all: 0, inside: 0 }
        e.all += 1
        // «Поэтому», «Конечно», «Значит» тоже с большой буквы, но всегда
        // в начале фразы; к человеку хоть раз да обратятся внутри
        if (w !== first || words.filter((x) => x === w).length > 1) e.inside += 1
        if (you && !polite) e.kid += 1
        if (polite && !you) e.mom += 1
        seen.set(w, e)
      }
    }
  }

  const names = [...seen.entries()].filter(([, e]) => e.all >= 3 && e.inside >= 1)
  const kid = names.filter(([, e]) => e.kid > e.mom).sort((a, b) => b[1].kid - a[1].kid)[0]
  const mom = names.filter(([, e]) => e.mom > e.kid).sort((a, b) => b[1].mom - a[1].mom)[0]
  return { kid: kid?.[0], mom: mom?.[0] }
}

export function buildDossier(utterances: Utterance[]): Dossier {
  const found = new Map<string, DossierEntry>()

  const put = (entry: DossierEntry) => {
    const was = found.get(entry.field.id)
    if (was && TRUST[was.source] > TRUST[entry.source]) return
    found.set(entry.field.id, entry)
  }

  /** Вопрос Егора, на который мама ещё отвечает */
  let asked = { text: '', at: 0, left: 0 }
  /** Вывод Егора, ждущий подтверждения */
  let checking: { entries: DossierEntry[]; left: number } | null = null

  for (let i = 0; i < utterances.length; i++) {
    const u = utterances[i]

    if (u.role === 'seller') {
      const question = questionPart(u.text)
      if (question) asked = { text: question, at: u.at, left: ANSWER_TURNS }
      // длинный рассказ про программу поминает и память, и телефон, и оценки:
      // согласие с ним ничего не говорит о ребёнке
      if (!question || u.text.length > 240 || !CHECKING.test(u.text)) {
        checking = null
        continue
      }
      const entries = matches(question, 'seller', u.at, 'agreed')
      // «во второй класс перешла, да? Да, да, да» — мамино согласие иногда
      // прилипает к реплике Егора, и отдельной реплики уже не будет
      const tail = u.text.slice(u.text.lastIndexOf('?') + 1).trim()
      if (tail && AGREE.test(tail) && !DISAGREE.test(tail)) {
        for (const entry of entries) put(entry)
        checking = null
      } else {
        checking = { entries, left: 2 }
      }
      continue
    }

    const own = matches(u.text, u.role, u.at, 'said')
    for (const entry of own) put(entry)

    if (checking) {
      if (AGREE.test(u.text.trim()) && !DISAGREE.test(u.text.trim())) {
        for (const entry of checking.entries) put(entry)
        checking = null
      } else if (--checking.left <= 0) {
        checking = null
      }
    }

    // реплика уже назвала свою тему — отвечать ею на другой вопрос нельзя
    if (own.length || u.hasQuestion) continue
    const rest = meaningful(u.text)
    if (rest.length < 5 && !/\d/.test(u.text)) continue
    if (!asked.left || u.at - asked.at > ANSWER_SEC * 1000) continue
    asked.left--

    for (const field of DOSSIER_FIELDS) {
      if (!field.askCues?.some((re) => re.test(asked.text))) continue
      if (field.answer === FREE && rest.length < 12) continue
      if (field.answer && !field.answer.test(u.text)) continue
      const value = field.value?.(u.text) ?? u.text
      put({
        field,
        value: value.slice(0, 160),
        quote: u.text,
        role: u.role,
        at: u.at,
        source: 'reply',
      })
    }
  }

  if (!found.has('name')) {
    const { kid } = guessNames(utterances)
    const field = DOSSIER_FIELDS.find((f) => f.id === 'name')
    if (kid && field) {
      put({
        field,
        value: kid,
        quote: `вы весь звонок зовёте ребёнка «${kid}»`,
        role: 'seller',
        at: 0,
        source: 'said',
      })
    }
  }

  const entries = DOSSIER_FIELDS.map((f) => found.get(f.id)).filter(Boolean) as DossierEntry[]
  const missing = DOSSIER_FIELDS.filter((f) => !found.has(f.id) && f.ask)

  return {
    entries,
    bySection: SECTIONS.map((section) => ({
      section,
      entries: entries.filter((e) => e.field.section === section),
    })).filter((s) => s.entries.length),
    missing,
    done: entries.length,
    total: DOSSIER_FIELDS.length,
    pointBFound: found.has('wish') || found.has('momEmotion'),
  }
}

/** Текст карточки для куратора и для истории встречи */
export function dossierText(dossier: Dossier): string {
  if (!dossier.entries.length) return ''
  const lines: string[] = []
  for (const { section, entries } of dossier.bySection) {
    lines.push(SECTION_TITLE[section])
    for (const e of entries) {
      const how = e.source === 'agreed' ? ' (подтвердила)' : e.role === 'kid' ? ' (со слов ребёнка)' : ''
      lines.push(`— ${e.field.title}: ${e.value}${how}`)
    }
    lines.push('')
  }
  return lines.join('\n').trim()
}
