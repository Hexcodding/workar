export type PointBCard = {
  /** id слота → ответ мамы (или пустая строка, если слот только прозвучал) */
  filled: Record<string, string>
  missing: PointBSlot[]
  done: number
  total: number
  /** следующий слот, который надо закрыть */
  next: PointBSlot | null
}

/**
 * Карточка точки Б: что уже оцифровано, а что нет.
 * Ответ мамы ищем в её реплике сразу после вопроса — так же, как в корпусе.
 */
export function buildPointBCard(utterances: Utterance[], sellerText = ''): PointBCard {
  const filled: Record<string, string> = {}
  const saidAll = stemsOf(sellerText)

  for (const slot of POINT_B_SLOTS) {
    let answer = ''
    let asked = false

    for (let i = 0; i < utterances.length; i++) {
      const u = utterances[i]
      if (u.role !== 'seller') continue
      if (hits(stemsOf(u.text), slot.keys) < slot.min) continue
      asked = true
      // на «мечту» отвечает ребёнок, на остальное мама — берём любого, кроме себя
      const reply = utterances.slice(i + 1, i + 4).find((x) => x.role !== 'seller')
      if (!reply) continue
      if (!slot.answerCues || slot.answerCues.some((re) => re.test(reply.text))) {
        answer = reply.text.slice(0, 160)
        break
      }
    }

    if (!asked && hits(saidAll, slot.keys) >= slot.min) asked = true
    if (asked) filled[slot.id] = answer
  }

  const missing = POINT_B_SLOTS.filter((s) => !(s.id in filled))
  return {
    filled,
    missing,
    done: Object.keys(filled).length,
    total: POINT_B_SLOTS.length,
    next: missing[0] ?? null,
  }
}

