export function fillTemplate(
  text: string,
  vars: { mom: string; child: string; seller: string },
): string {
  return text
    .replaceAll('{{mom}}', vars.mom || 'ИМЯ мамы')
    .replaceAll('{{child}}', vars.child || 'ИМЯ ребёнка')
    .replaceAll('{{seller}}', vars.seller || 'ИМЯ')
}

export function allItemIds(): string[] {
  return CHECKLIST.flatMap((stage) => stage.items.map((item) => item.id))
}

export function findItem(itemId: string): {
  stage: ChecklistStage
  item: ChecklistItem
  stageIndex: number
  itemIndex: number
} | null {
  for (let stageIndex = 0; stageIndex < CHECKLIST.length; stageIndex++) {
    const stage = CHECKLIST[stageIndex]
    const itemIndex = stage.items.findIndex((item) => item.id === itemId)
    if (itemIndex >= 0) {
      return { stage, item: stage.items[itemIndex], stageIndex, itemIndex }
    }
  }
  return null
}
