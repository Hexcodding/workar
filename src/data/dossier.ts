/** Скобки обязательны: без них перечисление разрывает любую составную примету */
const SUBJECTS =
  /(?:математик|алгебр|геометр|русск|литератур|истор|биолог|географ|физик|хими|англ|обществознан|информатик|окружающ)/

const SPLIT = /(?<=[.!?…])\s+/

/*
 * Окончания в приметах пишем как [а-яё]*, а конец слова как (?![а-яё]).
 * Готовые \w и \b в JavaScript латинские: «втор\w*» обрывается на первой же
 * русской букве, а «лет\b» не совпадает никогда — примета выглядит рабочей,
 * а на деле молчит.
 */

/** Предложение, в котором сработала примета: цитата должна быть по делу */
function sentence(text: string, re: RegExp): string {
  const parts = text.split(SPLIT)
  const hit = parts.find((p) => re.test(p))
  if (hit) return hit.trim()
  // примета легла через границу предложений — берём окно вокруг неё
  const at = text.search(re)
  if (at < 0) return text.trim()
  return text.slice(Math.max(0, at - 40), at + 120).trim()
}

const ASKING =
  /^(а |и |ну |скажите|подскажите|расскажи|какой|кака|каки|сколько|как |что |чем |почему|зачем|когда|где|кто |бывает|бывают|есть ли|часто ли|долго ли|правильно|верно|насколько|оцените|представьте|давайте представим)/i

/**
 * Вопросительная часть реплики Егора.
 *
 * Он подолгу объясняет про память, внимание и мотивацию, и если искать тему
 * во всей реплике, то любое «конечно, спасибо» после его рассказа улетит
 * в карточку как ответ. Спрашивает он в конце — оттуда и берём.
 */
function questionPart(text: string): string {
  const parts = text.split(SPLIT)
  const asks = parts.filter((p) => p.includes('?') || ASKING.test(p.trim()))
  return asks.slice(-2).join(' ')
}

function grab(text: string, re: RegExp): string | null {
  const m = text.match(re)
  return m ? m[0].trim() : null
}

/** Вежливость и поддакивания: как значение поля они бесполезны */
const FILLER_WORD =
  /^(да|нет|ага|угу|мгм|ну|вот|так|это|тоже|очень|окей|ок|ладно|хорошо|отлично|супер|понятно|ясно|видно|слышно|конечно|наверное|спасибо|пожалуйста|здравствуйте|извините|слушаю|можно|вс[её])$/i

/**
 * Ответ своими словами: на такие вопросы мама рассказывает, а не называет
 * цифру. От них требуем развёрнутости, иначе в поле попадает «уже пик».
 */
const FREE = /\S{4,}/

/** Что осталось в ответе, если убрать поддакивания */
function meaningful(text: string): string {
  return text
    .toLowerCase()
    .split(/[^а-яёa-z0-9]+/i)
    .filter((w) => w && !FILLER_WORD.test(w))
    .join(' ')
}

