/** Ход по последним словам мамы: первый подходящий, порядок в списке — приоритет */
export function pickSay(clientText: string, opts?: { priceNamed?: boolean }): SayMove | null {
  if (!clientText.trim()) return null
  for (const move of SAY_BANK) {
    if (move.beforePrice && opts?.priceNamed) continue
    if (move.not?.some((re) => re.test(clientText))) continue
    if (move.when.some((re) => re.test(clientText))) return move
  }
  return null
}
