/**
 * Что сказать, когда мама виляет.
 *
 * Ходы взяты из звонков Полины и Леонарда — у них закрытие выше, — но
 * переписаны языком Егора: «смотрите», «получается», «давайте», короткое
 * предложение, вопрос в конце. С экрана читается одна строка, поэтому длиннее
 * ста двадцати знаков фразы здесь быть не может: длинную не прочитать на
 * ходу, а читать её вслух по бумажке слышно в голосе.
 *
 * Это не замена мозгу: мозг ищет похожие куски в корпусе и часто приносит
 * абзац чужой стенограммы. Здесь — выжимка, которую можно произнести как есть.
 */

export type SayMove = {
  id: string
  /** что ты делаешь этим ходом */
  title: string
  /** фраза, которую можно сказать как есть */
  say: string
  /** чем добить, если первая зашла */
  then?: string
  /** почему это работает: нужно, чтобы не читать вслепую */
  because: string
  /** приметы в словах мамы */
  when: RegExp[]
  /** когда ход неуместен */
  not?: RegExp[]
  /** ход имеет смысл только до того, как названа цена */
  beforePrice?: boolean
}

