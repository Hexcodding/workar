/**
 * Главное правило наставника: за фразой мамы всегда стоит боль,
 * и работать надо с болью, а не с фразой.
 */
export function detectMomPain(text: string): MomPain | null {
  if (!text) return null
  let best: { pain: MomPain; hits: number } | null = null
  for (const pain of MOM_PAINS) {
    const hits = pain.cues.reduce((n, re) => n + (re.test(text) ? 1 : 0), 0)
    if (!hits) continue
    if (!best || hits > best.hits) best = { pain, hits }
  }
  return best?.pain ?? null
}

