/** Следующий вопрос ВП по порядку наставника, минуя уже заданные */
export function nextVpQuestion(
  sellerText: string,
  audience: 'parent' | 'kid' = 'parent',
): VpQuestion | null {
  const said = stemsOf(sellerText)
  const pending = VP_QUESTIONS.filter((q) => hits(said, q.keys) < q.min)
  return pending.find((q) => q.audience === audience) ?? pending[0] ?? null
}

/** Сколько вопросов ВП уже задано — для шапки и разбора после звонка */
export function vpProgress(sellerText: string): number {
  const said = stemsOf(sellerText)
  return VP_QUESTIONS.filter((q) => hits(said, q.keys) >= q.min).length
}

