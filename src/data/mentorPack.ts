/**
 * Слой «эталон наставника»: приоритет выше корпуса.
 * Корпус показывает, как продают в реальности, наставники — как надо,
 * поэтому при расхождении выигрывает этот файл.
 *
 * Источник: materials/mentor (голосовые + разборы + схема точки Б).
 */
import type { Utterance } from '../lib/dialogMeter'
import { stem } from '../lib/ruText'

/**
 * Живое распознавание коверкает слова («диагнозчик» вместо «диагностику»),
 * поэтому вопросы узнаём по основам слов, а не по точным формулировкам.
 */
const norm = (word: string) => stem(word.toLowerCase().replace(/ё/g, 'е'))

function stemsOf(text: string): Set<string> {
  return new Set(
    text
      .toLowerCase()
      .replace(/ё/g, 'е')
      .replace(/[^\p{L}\p{N}\s]/gu, ' ')
      .split(/\s+/)
      .filter((w) => w.length >= 3)
      .map(norm),
  )
}

function hits(said: Set<string>, keys: string[]): number {
  let n = 0
  for (const key of keys) if (said.has(norm(key))) n += 1
  return n
}

